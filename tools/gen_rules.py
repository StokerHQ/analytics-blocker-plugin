"""Compiles rules/hosts.yaml into src/generated/rules.h, the table the plugin carries.

    python3 tools/gen_rules.py           write the header
    python3 tools/gen_rules.py --check   exit 1 when the committed header is not what the rules generate

The rules are checked as they are compiled: a name must be lower-case ASCII (punycode for anything else) made of valid
labels, a wildcard is only a leading "*.", every rule names a known category, its vendor and how it was learned, no
name appears twice, and a rule has no key this version does not understand - a "paths" rule is refused until the
plugin can apply one. Needs PyYAML.
"""
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = ROOT / "rules" / "hosts.yaml"
HEADER = ROOT / "src" / "generated" / "rules.h"

CATEGORIES = {"analytics": "Analytics", "attribution": "Attribution", "crash": "Crash", "engine": "Engine"}
KEYS = {"match", "category", "vendor", "source"}
LABEL = re.compile(r"^(?!-)[a-z0-9-]{1,63}(?<!-)$")
TITLE_HINT = re.compile(r"\b(game|title)\s*:", re.IGNORECASE)


def fail(message):
    sys.exit(f"{RULES.relative_to(ROOT)}: {message}")


def c_string(text):
    if any(ord(c) < 0x20 or ord(c) > 0x7E for c in text) or '"' in text or "\\" in text:
        fail(f"{text!r} must be printable ASCII without quotes or backslashes")
    return f'"{text}"'


def compile_rules():
    document = yaml.safe_load(RULES.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or not isinstance(document.get("rules"), list):
        fail("expected a top-level 'rules' list")
    seen = set()
    rows = []
    for index, rule in enumerate(document["rules"]):
        where = f"rule {index + 1}"
        if not isinstance(rule, dict):
            fail(f"{where} is not a mapping")
        unknown = set(rule) - KEYS
        if unknown:
            fail(f"{where} has {', '.join(sorted(unknown))}, which this version does not apply")
        missing = KEYS - set(rule)
        if missing:
            fail(f"{where} lacks {', '.join(sorted(missing))}")
        match = str(rule["match"])
        subdomains = match.startswith("*.")
        name = match[2:] if subdomains else match
        if name != name.lower() or "*" in name or name.endswith("."):
            fail(f"{where}: '{match}' must be lower case, with at most a leading '*.' and no trailing dot")
        labels = name.split(".")
        if len(labels) < 2 or not all(LABEL.match(label) for label in labels) or len(name) > 253:
            fail(f"{where}: '{match}' is not a host name")
        if name in seen:
            fail(f"{where}: '{name}' appears twice")
        seen.add(name)
        category = rule["category"]
        if category not in CATEGORIES:
            fail(f"{where}: category '{category}' is not one of {', '.join(CATEGORIES)}")
        source = str(rule["source"])
        if TITLE_HINT.search(source):
            fail(f"{where}: a source says how a rule was learned, never which game")
        rows.append((name, subdomains, CATEGORIES[category], str(rule["vendor"])))
    return rows


def render(rows):
    lines = [
        "// Generated by tools/gen_rules.py from rules/hosts.yaml. Edit the rules, then run the generator.",
        "#pragma once",
        "",
        '#include "../core/rules.h"',
        "",
        "namespace analytics_blocker::generated",
        "{",
        "    inline constexpr Rule kRules[] = {",
    ]
    for name, subdomains, category, vendor in rows:
        lines.append(f"        {{{c_string(name)}, {'true' if subdomains else 'false'}, Category::{category}, {c_string(vendor)}}},")
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def main():
    text = render(compile_rules())
    if "--check" in sys.argv[1:]:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            sys.exit(f"{HEADER.relative_to(ROOT)} is not what {RULES.relative_to(ROOT)} generates; run tools/gen_rules.py")
        return
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
